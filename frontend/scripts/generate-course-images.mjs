// Writes lib/course-images.generated.ts: the image files in public/images/courses/.
// Runs before `next dev` and `next build` (predev/prebuild), so a newly added image
// is picked up without code edits. Matching files to course names happens in lib/courses.ts.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public/images/courses");
const out = join(root, "lib/course-images.generated.ts");
const EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".avif"]);

const files = readdirSync(dir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && EXTENSIONS.has(extname(entry.name).toLowerCase()))
  .map((entry) => entry.name)
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const content = `// Generated by scripts/generate-course-images.mjs — do not edit by hand.
// Files in public/images/courses/, sorted (the first file wins if two match one course).
export const COURSE_IMAGE_FILES: readonly string[] = ${JSON.stringify(files, null, 2)};
`;

let previous = "";
try {
  previous = readFileSync(out, "utf8");
} catch {}
if (previous !== content) writeFileSync(out, content);
console.log(`[course-images] ${files.length} image(s) in public/images/courses/`);
